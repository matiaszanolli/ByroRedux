//! Sub-records no parser decodes, kept as opaque bytes (PRD legacy-mod-compatibility LMC-REC-010).
//!
//! A parser reads the sub-records it knows and ignores the rest, so a mod's edit to a field the engine has no decoder
//! for left no trace: the record was parsed, the field was dropped, and nothing said so. [`OpaqueCollector`] keeps what
//! is dropped. The reader hands it every record's sub-records as it reads them; the ones `data/decoded_subrecords.toml`
//! does not list as decoded for the record type are stored, with the record's form ID, and a record no parser reads at
//! all (a group nobody consumes) is stored whole. The plugin's parse returns them as [`OpaqueRecord`]s; the load-order
//! fold stamps each with the plugin that carried it ([`OpaqueStore`]), so the conflict report can say which mod touched
//! a field the engine ignores.
//!
//! The table is data, not code: it is measured by [`super::decode_probe`], which asks the parsers, and regenerated by
//! `examples/inspect.rs decoded-subrecords`. A game or record type it has no entry for decodes nothing, so everything of
//! it is kept: the table can only err toward keeping bytes.

use std::collections::{BTreeMap, HashMap, HashSet};
use std::sync::OnceLock;

use anyhow::{Context, Result};

use super::reader::{GameKind, SubRecord};

/// The embedded table: per game, per record type, the sub-record tags the parsers decode.
const DECODED_TABLE: &str = include_str!("../../data/decoded_subrecords.toml");

/// Which sub-records the parsers decode, per game and record type.
#[derive(Debug, Default)]
pub struct DecodedTable {
    games: HashMap<String, HashMap<[u8; 4], HashSet<[u8; 4]>>>,
}

/// A tag as the table writes it: printable ASCII as itself, any other byte (IMAD's sub-records are named `\x14IAD`,
/// `\x06IAD`, …) and `%` as `%HH`, so the file holds only characters TOML takes unescaped.
pub fn encode_tag(tag: &[u8; 4]) -> String {
    tag.iter()
        .map(|&byte| match byte {
            b'%' | 0..=0x1f | 0x7f..=0xff | b'"' | b'\\' => format!("%{byte:02X}"),
            _ => char::from(byte).to_string(),
        })
        .collect()
}

/// The four bytes [`encode_tag`] wrote as `text`.
pub fn decode_tag(text: &str) -> Result<[u8; 4]> {
    let bytes = text.as_bytes();
    let mut tag = Vec::with_capacity(4);
    let mut at = 0;
    while at < bytes.len() {
        if bytes[at] == b'%' {
            let hex = text.get(at + 1..at + 3).with_context(|| format!("'{text}': a '%' without two hex digits"))?;
            tag.push(u8::from_str_radix(hex, 16).with_context(|| format!("'{text}': '%{hex}' is not hex"))?);
            at += 3;
        } else {
            tag.push(bytes[at]);
            at += 1;
        }
    }
    <[u8; 4]>::try_from(tag).map_err(|_| anyhow::anyhow!("'{text}' is not a four-byte tag"))
}

impl DecodedTable {
    /// Read a table from its TOML text: `[game]`, then `"TYPE" = ["TAG", …]`.
    pub fn parse(text: &str) -> Result<Self> {
        let raw: BTreeMap<String, BTreeMap<String, Vec<String>>> = toml::from_str(text).context("decoded-subrecords table")?;
        let mut games = HashMap::new();
        for (game, types) in raw {
            let mut by_type = HashMap::new();
            for (record_type, tags) in types {
                let tags = tags.iter().map(|tag| decode_tag(tag)).collect::<Result<HashSet<_>>>()?;
                by_type.insert(decode_tag(&record_type)?, tags);
            }
            games.insert(game, by_type);
        }
        Ok(Self { games })
    }

    /// The table's key for `game`.
    pub fn game_key(game: GameKind) -> &'static str {
        match game {
            GameKind::Oblivion => "oblivion",
            GameKind::Fallout3NV => "fallout3nv",
            GameKind::Skyrim => "skyrim",
            GameKind::Fallout4 => "fallout4",
            GameKind::Fallout76 => "fallout76",
            GameKind::Starfield => "starfield",
        }
    }

    /// The table's section for `game`: per record type, the sub-record tags the parsers decode.
    pub fn section(&self, game: GameKind) -> Option<crate::esm::decode_probe::Decoded> {
        let types = self.games.get(Self::game_key(game))?;
        Some(types.iter().map(|(record_type, tags)| (*record_type, tags.iter().copied().collect())).collect())
    }

    /// Whether the table was derived for `game`. Without it every sub-record counts as undecoded.
    pub fn knows(&self, game: GameKind) -> bool {
        self.games.contains_key(Self::game_key(game))
    }

    /// Whether the parsers decode `tag` of a `record_type` record. A record type the table has no entry for decodes
    /// nothing.
    pub fn is_decoded(&self, game: GameKind, record_type: [u8; 4], tag: [u8; 4]) -> bool {
        self.games.get(Self::game_key(game)).and_then(|types| types.get(&record_type)).is_some_and(|tags| tags.contains(&tag))
    }
}

/// The table compiled into the engine.
pub fn decoded_table() -> &'static DecodedTable {
    static TABLE: OnceLock<DecodedTable> = OnceLock::new();
    TABLE.get_or_init(|| DecodedTable::parse(DECODED_TABLE).expect("data/decoded_subrecords.toml is well formed (a test parses it)"))
}

/// One sub-record no parser decoded.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OpaqueSubRecord {
    pub tag: [u8; 4],
    pub data: Vec<u8>,
}

/// The sub-records of one record that no parser decoded, in the record's order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OpaqueRecord {
    pub record_type: [u8; 4],
    pub subrecords: Vec<OpaqueSubRecord>,
}

/// What the reader gathers while a plugin is parsed.
#[derive(Debug)]
pub struct OpaqueCollector {
    game: GameKind,
    records: HashMap<u32, OpaqueRecord>,
}

impl OpaqueCollector {
    pub fn new(game: GameKind) -> Self {
        Self { game, records: HashMap::new() }
    }

    /// A record a parser read: keep the sub-records the table does not list as decoded for its type.
    pub fn note_read(&mut self, record_type: [u8; 4], form_id: u32, subs: &[SubRecord]) {
        let table = decoded_table();
        let undecoded: Vec<OpaqueSubRecord> = subs
            .iter()
            .filter(|sub| !table.is_decoded(self.game, record_type, sub.sub_type))
            .map(|sub| OpaqueSubRecord { tag: sub.sub_type, data: sub.data.clone() })
            .collect();
        self.store(record_type, form_id, undecoded);
    }

    /// A record no parser read: all of it is undecoded.
    pub fn note_skipped(&mut self, record_type: [u8; 4], form_id: u32, subs: &[SubRecord]) {
        let all = subs.iter().map(|sub| OpaqueSubRecord { tag: sub.sub_type, data: sub.data.clone() }).collect();
        self.store(record_type, form_id, all);
    }

    fn store(&mut self, record_type: [u8; 4], form_id: u32, subrecords: Vec<OpaqueSubRecord>) {
        if subrecords.is_empty() {
            self.records.remove(&form_id);
        } else {
            self.records.insert(form_id, OpaqueRecord { record_type, subrecords });
        }
    }

    /// The records gathered, by form ID.
    pub fn into_records(self) -> HashMap<u32, OpaqueRecord> {
        self.records
    }
}

/// One plugin's opaque sub-records of a form.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OpaqueCarrier {
    /// The plugin's load-order position.
    pub plugin: u32,
    pub record: OpaqueRecord,
}

/// The undecoded sub-records of every form, by the plugin that carried them, in load order. Built by the fold beside
/// its provenance; a form a plugin overrides keeps every carrier's, because a loser's field is still one a mod touched.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct OpaqueStore {
    by_form: HashMap<u32, Vec<OpaqueCarrier>>,
}

impl OpaqueStore {
    /// Record what the plugin at load-order `position` carried that no parser decoded.
    pub fn note_plugin(&mut self, position: usize, records: HashMap<u32, OpaqueRecord>) {
        for (form_id, record) in records {
            self.by_form.entry(form_id).or_default().push(OpaqueCarrier { plugin: position as u32, record });
        }
    }

    /// The carriers of `form_id` that held undecoded sub-records, in load order.
    pub fn carriers(&self, form_id: u32) -> &[OpaqueCarrier] {
        self.by_form.get(&form_id).map_or(&[], Vec::as_slice)
    }

    /// How many forms hold undecoded sub-records, and how many sub-records and bytes in all.
    pub fn counts(&self) -> (usize, usize, usize) {
        let carriers = self.by_form.values().flatten();
        let (subs, bytes) = carriers.fold((0, 0), |(subs, bytes), carrier| {
            (subs + carrier.record.subrecords.len(), bytes + carrier.record.subrecords.iter().map(|sub| sub.data.len()).sum::<usize>())
        });
        (self.by_form.len(), subs, bytes)
    }

    /// Per plugin position: the forms it carried with undecoded sub-records, and how many sub-records.
    pub fn per_plugin(&self) -> BTreeMap<u32, (usize, usize)> {
        let mut out: BTreeMap<u32, (usize, usize)> = BTreeMap::new();
        for carrier in self.by_form.values().flatten() {
            let entry = out.entry(carrier.plugin).or_default();
            entry.0 += 1;
            entry.1 += carrier.record.subrecords.len();
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::esm::records::test_support::sub;

    /// The embedded table parses and holds every game it was derived for.
    #[test]
    fn the_embedded_table_parses_and_covers_the_games() {
        let table = decoded_table();
        for game in [GameKind::Oblivion, GameKind::Fallout3NV, GameKind::Skyrim, GameKind::Fallout4, GameKind::Fallout76, GameKind::Starfield] {
            assert!(table.knows(game), "{game:?} has no section in data/decoded_subrecords.toml");
            assert!(table.is_decoded(game, *b"MISC", *b"EDID"), "{game:?}: MISC's EDID is decoded");
        }
    }

    #[test]
    fn a_table_lists_decoded_tags_per_game_and_record_type() {
        let table = DecodedTable::parse("[skyrim]\n\"WEAP\" = [\"EDID\", \"DNAM\"]\n\"IDLM\" = []\n").unwrap();
        assert!(table.is_decoded(GameKind::Skyrim, *b"WEAP", *b"DNAM"));
        assert!(!table.is_decoded(GameKind::Skyrim, *b"WEAP", *b"CRDT"), "a tag the list lacks");
        assert!(!table.is_decoded(GameKind::Skyrim, *b"IDLM", *b"EDID"), "a probed type that decodes nothing");
        assert!(!table.is_decoded(GameKind::Skyrim, *b"ARMO", *b"EDID"), "a type the table has no entry for decodes nothing");
        assert!(!table.is_decoded(GameKind::Fallout4, *b"WEAP", *b"DNAM"), "a game the table has no section for");
        assert!(table.knows(GameKind::Skyrim) && !table.knows(GameKind::Fallout4));
        assert!(DecodedTable::parse("[skyrim]\n\"WEAP\" = [\"TOOLONG\"]\n").is_err());
    }

    /// A read record keeps only what its table entry does not list, and a record that decodes everything keeps nothing.
    #[test]
    fn a_read_record_keeps_only_the_undecoded_sub_records() {
        let mut collector = OpaqueCollector::new(GameKind::Fallout3NV);
        collector.note_read(*b"MISC", 0x0100_0001, &[sub(b"EDID", b"A\0"), sub(b"ZZZZ", b"opaque"), sub(b"DATA", [0; 8])]);
        collector.note_read(*b"MISC", 0x0100_0002, &[sub(b"EDID", b"B\0"), sub(b"DATA", [0; 8])]);
        let records = collector.into_records();
        assert_eq!(
            records[&0x0100_0001],
            OpaqueRecord { record_type: *b"MISC", subrecords: vec![OpaqueSubRecord { tag: *b"ZZZZ", data: b"opaque".to_vec() }] }
        );
        assert!(!records.contains_key(&0x0100_0002), "nothing undecoded, nothing kept");
    }

    /// The file opens with the header `inspect decoded-subrecords` writes, so regenerating it changes only the sections.
    #[test]
    fn the_table_file_opens_with_the_generated_header() {
        assert!(DECODED_TABLE.starts_with(&format!("{}\n", crate::esm::decode_probe::TABLE_HEADER)), "regenerate data/decoded_subrecords.toml");
    }

    /// Tags with control bytes, quotes or percent signs survive the table's text form.
    #[test]
    fn tags_round_trip_through_the_table_text() {
        for tag in [*b"EDID", [0x14, b'I', b'A', b'D'], *b"%A\"\\", [0xe9, 0x00, 0x7f, b' '], *b"NPC_"] {
            let text = encode_tag(&tag);
            assert!(text.bytes().all(|byte| (0x20..0x7f).contains(&byte) && byte != b'"' && byte != b'\\'), "{text}");
            assert_eq!(decode_tag(&text).unwrap(), tag, "{text}");
        }
        assert_eq!(encode_tag(&[0x14, b'I', b'A', b'D']), "%14IAD");
        assert!(decode_tag("%1").is_err() && decode_tag("%ZZAB").is_err() && decode_tag("ABC").is_err());
    }

    #[test]
    fn a_skipped_record_is_kept_whole() {
        let mut collector = OpaqueCollector::new(GameKind::Fallout3NV);
        collector.note_skipped(*b"MISC", 0x0100_0003, &[sub(b"EDID", b"C\0"), sub(b"DATA", [1; 8])]);
        let records = collector.into_records();
        assert_eq!(records[&0x0100_0003].subrecords.len(), 2, "nobody read it, so the decoded table does not apply");
    }

    /// The store keeps every plugin's undecoded sub-records of a form, in load order, with the plugin that carried them.
    #[test]
    fn the_store_keeps_each_carrier_of_a_form() {
        let record = |data: &[u8]| OpaqueRecord {
            record_type: *b"WEAP",
            subrecords: vec![OpaqueSubRecord { tag: *b"ZZZZ", data: data.to_vec() }],
        };
        let mut store = OpaqueStore::default();
        store.note_plugin(1, HashMap::from([(0x0100_0010, record(b"a")), (0x0100_0011, record(b"bb"))]));
        store.note_plugin(3, HashMap::from([(0x0100_0010, record(b"ccc"))]));
        let carriers = store.carriers(0x0100_0010);
        assert_eq!(carriers.iter().map(|carrier| carrier.plugin).collect::<Vec<_>>(), [1, 3]);
        assert_eq!(store.counts(), (2, 3, 6));
        assert_eq!(store.per_plugin(), BTreeMap::from([(1, (2, 2)), (3, (1, 1))]));
        assert!(store.carriers(0x0100_9999).is_empty());
    }

    /// Real data (ignored: it needs the Unofficial Fallout 4 Patch): what the reader collects from a mod plugin is what an
    /// independent walk of its records says no parser decodes, by form and tag. The walk shares nothing with the reader
    /// but the table, so a record the reader reads through some other path, or skips, and the collector misses, shows as a
    /// difference. Nested records (references under a cell, responses under a topic) are in it.
    #[test]
    #[ignore = "needs the Unofficial Fallout 4 Patch in the Fallout 4 Data directory"]
    fn the_collected_sub_records_match_a_raw_walk_of_a_mod_plugin() {
        use crate::esm::decode_probe::{for_each_record, layout_of, sub_records};
        use crate::esm::records::{parse_esm_with_options, ParseOptions};
        let data_dir = crate::esm::test_paths::fo4_data_dir();
        let path = std::fs::read_dir(&data_dir).ok().and_then(|entries| {
            entries.flatten().map(|entry| entry.path()).find(|path| {
                path.file_name().is_some_and(|name| name.to_string_lossy().eq_ignore_ascii_case("unofficial fallout 4 patch.esp"))
            })
        });
        let Some(path) = path else {
            crate::esm::test_paths::require_or_skip("the Unofficial Fallout 4 Patch");
            return;
        };
        let bytes = std::fs::read(&path).unwrap();
        let index = parse_esm_with_options(&bytes, None, ParseOptions { collect_opaque: true }).expect("parse");
        assert_eq!(index.game, GameKind::Fallout4);

        let layout = layout_of(&bytes).unwrap();
        let mut expected: BTreeMap<u32, BTreeMap<[u8; 4], usize>> = BTreeMap::new();
        let table = decoded_table();
        for_each_record(&bytes, layout, |at, head| {
            if head.flags & 0x20 != 0 {
                return;
            }
            let Ok(subs) = sub_records(&bytes[at..at + layout.record + head.data_size], layout) else {
                return;
            };
            for (tag, _) in subs {
                if !table.is_decoded(GameKind::Fallout4, head.record_type, tag) {
                    *expected.entry(head.form_id).or_default().entry(tag).or_default() += 1;
                }
            }
        });
        let mut actual: BTreeMap<u32, BTreeMap<[u8; 4], usize>> = BTreeMap::new();
        for (form_id, record) in &index.opaque_subrecords {
            for sub in &record.subrecords {
                *actual.entry(*form_id).or_default().entry(sub.tag).or_default() += 1;
            }
        }
        let missed: Vec<_> = expected.iter().filter(|(form, tags)| actual.get(form) != Some(tags)).take(8).collect();
        let extra: Vec<_> = actual.iter().filter(|(form, _)| !expected.contains_key(form)).take(8).collect();
        let (subs, held): (usize, usize) = index
            .opaque_subrecords
            .values()
            .flat_map(|record| &record.subrecords)
            .fold((0, 0), |(subs, held), sub| (subs + 1, held + sub.data.len()));
        let mut by_tag: BTreeMap<([u8; 4], [u8; 4]), (usize, usize)> = BTreeMap::new();
        for record in index.opaque_subrecords.values() {
            for sub in &record.subrecords {
                let entry = by_tag.entry((record.record_type, sub.tag)).or_default();
                entry.0 += 1;
                entry.1 += sub.data.len();
            }
        }
        let mut heaviest: Vec<_> = by_tag.into_iter().collect();
        heaviest.sort_unstable_by_key(|(_, (_, bytes))| std::cmp::Reverse(*bytes));
        for ((record_type, tag), (count, bytes)) in heaviest.iter().take(6) {
            eprintln!("  {} {}: {count} sub-records, {bytes} bytes", encode_tag(record_type), encode_tag(tag));
        }
        let timed = |collect_opaque| {
            let started = std::time::Instant::now();
            parse_esm_with_options(&bytes, None, ParseOptions { collect_opaque }).expect("parse");
            started.elapsed().as_secs_f64()
        };
        eprintln!(
            "{} bytes of plugin: {subs} undecoded sub-records, {held} bytes held; parse {:.2}s without, {:.2}s with",
            bytes.len(),
            timed(false),
            timed(true)
        );
        eprintln!("expected {} forms, collected {}; missed {:?}; extra {:?}", expected.len(), actual.len(), missed, extra);
        assert!(expected.len() > 1000, "the patch holds undecoded sub-records ({} forms)", expected.len());
        assert!(missed.is_empty() && extra.is_empty(), "missed {missed:?}, extra {extra:?}");
    }
}
