use std::path::Path;
use std::time::{Duration, SystemTime};

use super::*;

/// A TES4-only plugin; `master` sets the record's master flag (0x1).
fn plugin(dir: &Path, name: &str, master: bool, minutes: u64) {
    let mut bytes = b"TES4".to_vec();
    bytes.extend_from_slice(&0u32.to_le_bytes());
    bytes.extend_from_slice(&(master as u32).to_le_bytes());
    bytes.extend_from_slice(&[0u8; 12]);
    std::fs::write(dir.join(name), &bytes).unwrap();
    let file = std::fs::File::options().write(true).open(dir.join(name)).unwrap();
    file.set_modified(SystemTime::UNIX_EPOCH + Duration::from_secs(1_000_000 + minutes * 60)).unwrap();
}

fn names(profile: &ImportedProfile) -> Vec<&str> {
    profile.plugins.iter().map(|p| p.name.as_str()).collect()
}

fn fnv_rules() -> GameRules {
    rules_for(GameKind::Fallout3NV, 1.34, 15).unwrap()
}

#[test]
fn a_plugin_list_skips_comments_and_keeps_the_asterisk() {
    let list = parse_plugin_list(b"# header\r\n*Skyrim.esm\r\n\r\nInactive.esp\r\n*Caf\xe9.esp\r\n");
    assert_eq!(
        list,
        vec![
            ListEntry { name: "Skyrim.esm".into(), starred: true },
            ListEntry { name: "Inactive.esp".into(), starred: false },
            // 0xE9 is not UTF-8 on its own: decoded as Windows-1252.
            ListEntry { name: "Café.esp".into(), starred: true },
        ]
    );
}

#[test]
fn a_modlist_reads_lowest_priority_first_without_separators_or_overwrite() {
    let text = "# This file was automatically generated by Mod Organizer.\r\n+Top Mod\r\n-Off Mod\r\n\
                +Patches_separator\r\n*Unmanaged: DLC\r\n+Bottom Mod\r\noverwrite\r\n";
    let mods = parse_modlist(text);
    assert_eq!(
        mods,
        vec![
            ModlistEntry { name: "Bottom Mod".into(), state: ModState::Enabled },
            ModlistEntry { name: "Unmanaged: DLC".into(), state: ModState::Foreign },
            ModlistEntry { name: "Off Mod".into(), state: ModState::Disabled },
            ModlistEntry { name: "Top Mod".into(), state: ModState::Enabled },
        ]
    );
}

#[test]
fn mo2_directories_follow_the_ini_or_default_beside_it() {
    let dir = Path::new("/mo2");
    let (mods, overwrite, notes) = mo2_directories("[General]\ngameName=New Vegas\n", dir);
    assert_eq!((mods, overwrite), (dir.join("mods"), dir.join("overwrite")));
    assert!(notes.is_empty());
    let ini = "[Settings]\nbase_directory=Z:/games/mo2\nmod_directory=%BASE_DIR%/my mods\noverwrite_directory=C:/ow\n";
    let (mods, overwrite, notes) = mo2_directories(ini, dir);
    assert_eq!(mods, PathBuf::from("/games/mo2/my mods"));
    assert_eq!(overwrite, PathBuf::from("C:/ow"));
    assert_eq!(notes.len(), 1, "{notes:?}");
}

