#[test]
fn a_vortex_manifest_parses_and_a_future_version_is_refused() {
    let text = r#"{"instance":"x","version":1,"deploymentMethod":"hardlink_activator","gameId":"fallout4",
        "stagingPath":"Z:\\stage","targetPath":"Z:\\game\\Data",
        "files":[{"relPath":"a\\b.dds","source":"ModA","target":"","time":1}]}"#;
    let deployment = parse_vortex_deployment(text).unwrap();
    assert_eq!(deployment.staging_path, "Z:\\stage");
    assert_eq!(deployment.files, vec![("a\\b.dds".to_owned(), "ModA".to_owned())]);
    assert!(parse_vortex_deployment(&text.replace("\"version\":1", "\"version\":2")).is_err());
}

#[test]
fn roots_are_ordered_so_each_deployed_file_wins() {
    let mods: Vec<String> = ["A", "B", "C"].iter().map(|s| s.to_string()).collect();
    // B's x.dds was deployed over A's and C's; A's y.dds over C's.
    let winners = vec![("x.dds".to_owned(), "B".to_owned()), ("y.dds".to_owned(), "A".to_owned())];
    let carries = |name: &str, path: &str| matches!((name, path), (_, "x.dds") | ("A" | "C", "y.dds"));
    let (order, notes) = order_by_winners(&mods, &winners, carries);
    assert_eq!(order, vec!["C", "A", "B"]);
    assert!(notes.is_empty());
    // A over B on one file, B over A on another: a cycle, reported, name order kept.
    let winners = vec![("x".to_owned(), "A".to_owned()), ("y".to_owned(), "B".to_owned())];
    let (order, notes) = order_by_winners(&mods[..2], &winners, |_, _| true);
    assert_eq!(order, vec!["A", "B"]);
    assert_eq!(notes.len(), 1);
}

#[test]
fn rules_follow_the_game_the_base_master_names() {
    assert_eq!(fnv_rules().method, LoadOrderMethod::Timestamp);
    assert!(fnv_rules().nam_activation);
    let fo3 = rules_for(GameKind::Fallout3NV, 0.94, 15).unwrap();
    assert!(!fo3.nam_activation);
    assert_eq!(fo3.always_active, &["Fallout3.esm"]);
    assert_eq!(rules_for(GameKind::Skyrim, 0.94, 40).unwrap().method, LoadOrderMethod::Textfile);
    let se = rules_for(GameKind::Skyrim, 1.71, 44).unwrap();
    assert_eq!((se.method, se.ccc), (LoadOrderMethod::Asterisk, Some("Skyrim.ccc")));
    assert_eq!(rules_for(GameKind::Fallout4, 1.0, 131).unwrap().early[0], "Fallout4.esm");
}

