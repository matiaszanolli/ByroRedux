#[test]
fn new_vegas_orders_by_file_time_masters_first_and_nam_files_activate() {
    let tmp = tempfile::tempdir().unwrap();
    let data = tmp.path().join("Data");
    std::fs::create_dir(&data).unwrap();
    plugin(&data, "FalloutNV.esm", true, 0);
    plugin(&data, "DeadMoney.esm", true, 5);
    plugin(&data, "Early.esp", false, 1); // older than DeadMoney.esm, but a master loads first
    plugin(&data, "Late.esp", false, 9);
    plugin(&data, "Inactive.esp", false, 3);
    std::fs::write(data.join("DeadMoney.nam"), "").unwrap();
    std::fs::write(tmp.path().join("plugins.txt"), "# active\r\nLate.esp\r\nEarly.esp\r\nMissing.esp\r\n").unwrap();
    let sources = [ImportSource::PluginsTxt(tmp.path().join("plugins.txt"))];
    let profile = import(&sources, &data, &fnv_rules());
    assert_eq!(names(&profile), vec!["FalloutNV.esm", "DeadMoney.esm", "Early.esp", "Late.esp"]);
    assert!(profile.notes.iter().any(|n| n.starts_with("Missing.esp: active, but in neither Data")), "{:?}", profile.notes);
    assert!(profile.notes.iter().any(|n| n == "1 inactive plugin(s) left out"), "{:?}", profile.notes);
}

#[test]
fn skyrim_se_loads_early_and_creation_club_plugins_first_then_the_asterisk_list() {
    let tmp = tempfile::tempdir().unwrap();
    let data = tmp.path().join("Data");
    std::fs::create_dir(&data).unwrap();
    for name in ["Skyrim.esm", "Update.esm", "Dawnguard.esm", "ccBGSSSE001-Fish.esm", "Mod.esp", "Off.esp"] {
        plugin(&data, name, name.ends_with(".esm"), 0);
    }
    // HearthFires and Dragonborn are not installed; the .ccc names one installed and one absent plugin.
    std::fs::write(tmp.path().join("Skyrim.ccc"), "ccBGSSSE001-Fish.esm\r\nccAbsent.esl\r\n").unwrap();
    std::fs::write(tmp.path().join("Plugins.txt"), "*Mod.esp\r\nOff.esp\r\n").unwrap();
    let rules = rules_for(GameKind::Skyrim, 1.71, 44).unwrap();
    let profile = import(&[ImportSource::PluginsTxt(tmp.path().join("Plugins.txt"))], &data, &rules);
    assert_eq!(names(&profile), vec!["Skyrim.esm", "Update.esm", "Dawnguard.esm", "ccBGSSSE001-Fish.esm", "Mod.esp"]);
    let without = import(&[], &data, &rules);
    assert_eq!(without.plugins.len(), 4);
    assert!(without.notes.iter().any(|n| n.starts_with("no plugins.txt")));
}

#[test]
fn an_mo2_profile_gives_its_enabled_mods_as_roots_and_its_lists_the_order() {
    let tmp = tempfile::tempdir().unwrap();
    let data = tmp.path().join("Data");
    std::fs::create_dir(&data).unwrap();
    plugin(&data, "FalloutNV.esm", true, 0);
    let base = tmp.path().join("mo2");
    let profile = base.join("profiles/Default");
    std::fs::create_dir_all(&profile).unwrap();
    for (dir, plugin_name) in [("Low", "Low.esp"), ("High", "High.esp"), ("Off", "Off.esp")] {
        let mod_dir = base.join("mods").join(dir);
        std::fs::create_dir_all(&mod_dir).unwrap();
        plugin(&mod_dir, plugin_name, false, 0);
    }
    std::fs::create_dir_all(base.join("overwrite")).unwrap();
    std::fs::write(base.join("overwrite/generated.ini"), "").unwrap();
    std::fs::write(profile.join("modlist.txt"), "+High\r\n+Gone\r\n-Off\r\n+Low\r\n*DLC: Dead Money\r\n").unwrap();
    // MO2's Gamebryo-era profile: plugins.txt the active set, loadorder.txt the order.
    std::fs::write(profile.join("plugins.txt"), "FalloutNV.esm\r\nHigh.esp\r\nLow.esp\r\n").unwrap();
    std::fs::write(profile.join("loadorder.txt"), "FalloutNV.esm\r\nHigh.esp\r\nLow.esp\r\nOff.esp\r\n").unwrap();
    let imported = import(&[ImportSource::Mo2Profile(profile)], &data, &fnv_rules());
    let roots: Vec<String> =
        imported.roots.iter().map(|r| r.path.file_name().unwrap().to_string_lossy().into_owned()).collect();
    assert_eq!(roots, vec!["Low", "High", "overwrite"]);
    assert_eq!(names(&imported), vec!["FalloutNV.esm", "High.esp", "Low.esp"]);
    assert_eq!(imported.plugins[1].root, Some(1));
    assert_eq!(imported.plugins[0].root, None);
    let notes = imported.notes.join("\n");
    assert!(notes.contains("MO2 mod 'Gone': no directory"), "{notes}");
    assert!(notes.contains("1 disabled mod(s) left out"), "{notes}");
    assert!(notes.contains("1 foreign entr"), "{notes}");
}

#[test]
fn a_vortex_deployment_gives_its_staged_mods_as_roots_in_winning_order() {
    let tmp = tempfile::tempdir().unwrap();
    let data = tmp.path().join("Data");
    let staging = tmp.path().join("staging");
    std::fs::create_dir(&data).unwrap();
    plugin(&data, "Fallout4.esm", true, 0);
    for name in ["ModA", "ModB"] {
        let dir = staging.join(name).join("textures");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("shared.dds"), name).unwrap();
    }
    plugin(&staging.join("ModB"), "ModB.esp", false, 0);
    // ModA's copy of the shared texture was deployed; ModGone's staging folder no longer exists.
    let manifest = format!(
        r#"{{"version":1,"stagingPath":"{}","targetPath":"{}","deploymentMethod":"hardlink_activator",
            "files":[{{"relPath":"textures\\shared.dds","source":"ModA"}},{{"relPath":"ModB.esp","source":"ModB"}},
                     {{"relPath":"x.esp","source":"ModGone"}}]}}"#,
        staging.display(),
        data.display()
    );
    std::fs::write(data.join("vortex.deployment.json"), manifest).unwrap();
    std::fs::write(tmp.path().join("Plugins.txt"), "*ModB.esp\r\n").unwrap();
    let rules = rules_for(GameKind::Fallout4, 1.0, 131).unwrap();
    let sources = [ImportSource::detect(&data).unwrap(), ImportSource::PluginsTxt(tmp.path().join("Plugins.txt"))];
    let imported = import(&sources, &data, &rules);
    let roots: Vec<String> =
        imported.roots.iter().map(|r| r.path.file_name().unwrap().to_string_lossy().into_owned()).collect();
    assert_eq!(roots, vec!["ModB", "ModA"]);
    assert_eq!(names(&imported), vec!["Fallout4.esm", "ModB.esp"]);
    assert!(imported.notes.iter().any(|n| n.starts_with("Vortex mod 'ModGone': no staging folder")), "{:?}", imported.notes);
}
