#!/usr/bin/env python3
"""Generate crates/renderer/shaders/include/env_brdf_lut.glsl (M-LIGHT RLT-IBL-003).

The split-sum environment BRDF of Karis, "Real Shading in Unreal Engine 4"
(SIGGRAPH 2013 course notes, "Environment BRDF"), integrated exactly instead
of approximated by the 2014 mobile fit (`envBRDFApprox`): for each
(NdotV, roughness) at a 32 x 32 grid of texel centres,

    A = mean[(1 - Fc) G vh / (nh nv)],  B = mean[Fc G vh / (nh nv)]

over 4096 GGX-importance-sampled half vectors (Hammersley), with
alpha = roughness^2, Fc = (1 - vh)^5 and the separable exact Smith G1 for
GGX, the same lobe the reference renderer's rough BSDFs use (PRD V13). The
environment term is then `prefiltered * (F0 * A + B)`.

Deterministic: rerunning produces the same file byte for byte.
Usage: python3 scripts/gen_env_brdf_lut.py
"""
from pathlib import Path

import numpy as np

SIZE = 32
SAMPLES = 4096
OUT = Path(__file__).resolve().parent.parent / "crates/renderer/shaders/include/env_brdf_lut.glsl"


def hammersley(n: int) -> tuple[np.ndarray, np.ndarray]:
    i = np.arange(n, dtype=np.uint32)
    bits = i.copy()
    bits = ((bits << 16) | (bits >> 16)) & 0xFFFFFFFF
    bits = ((bits & 0x55555555) << 1) | ((bits & 0xAAAAAAAA) >> 1)
    bits = ((bits & 0x33333333) << 2) | ((bits & 0xCCCCCCCC) >> 2)
    bits = ((bits & 0x0F0F0F0F) << 4) | ((bits & 0xF0F0F0F0) >> 4)
    bits = ((bits & 0x00FF00FF) << 8) | ((bits & 0xFF00FF00) >> 8)
    return (i + 0.5) / n, bits.astype(np.float64) / 2.0 ** 32


def g1(c: "np.ndarray | float", a2: float) -> np.ndarray:
    c = np.maximum(c, 1e-6)
    return 2.0 / (1.0 + np.sqrt(1.0 + a2 * (1.0 - c * c) / (c * c)))


def integrate(nv: float, roughness: float, xi1: np.ndarray, xi2: np.ndarray) -> tuple[float, float]:
    alpha = max(roughness * roughness, 1e-4)
    a2 = alpha * alpha
    v = np.array([np.sqrt(1.0 - nv * nv), 0.0, nv])
    phi = 2.0 * np.pi * xi1
    ct = np.sqrt((1.0 - xi2) / (1.0 + (a2 - 1.0) * xi2))
    st = np.sqrt(np.maximum(0.0, 1.0 - ct * ct))
    h = np.stack([st * np.cos(phi), st * np.sin(phi), ct], axis=1)
    vh = h @ v
    l = 2.0 * vh[:, None] * h - v
    nl = l[:, 2]
    ok = (nl > 0.0) & (vh > 0.0)
    g = g1(nv, a2) * g1(nl, a2)
    w = np.where(ok, g * vh / (np.maximum(h[:, 2], 1e-6) * nv), 0.0)
    fc = (1.0 - np.clip(vh, 0.0, 1.0)) ** 5
    return float(((1.0 - fc) * w).mean()), float((fc * w).mean())


GLSL_OUT = OUT
RUST_OUT = Path(__file__).resolve().parent.parent / "crates/renderer/src/vulkan/scene_buffer/env_brdf_lut.rs"


def table() -> list[tuple[float, float]]:
    xi1, xi2 = hammersley(SAMPLES)
    out = []
    for j in range(SIZE):              # roughness
        r = (j + 0.5) / SIZE
        for i in range(SIZE):          # NdotV
            out.append(integrate((i + 0.5) / SIZE, r, xi1, xi2))
    return out


def render() -> tuple[str, str]:
    """(GLSL include, Rust data module). The table lives in a storage buffer
    (set 1, binding 26) the scene buffers fill once at creation: a 1024-entry
    constant array in the shader was lowered to per-invocation memory and cost
    the main pass +2 to +8.5 ms (PRD rev 48)."""
    values = ",\n    ".join(f"{a:.6f}, {b:.6f}" for a, b in table())
    glsl = f"""// GENERATED by scripts/gen_env_brdf_lut.py — do not edit by hand.
//
// M-LIGHT RLT-IBL-003: the split-sum environment BRDF (Karis 2013,
// "Environment BRDF"), integrated exactly with alpha = roughness^2 and the
// separable exact Smith G1 for GGX: a {SIZE} x {SIZE} table of (A, B) at texel
// centres, NdotV along x, roughness along y, in set 1 binding 26 (filled from
// `scene_buffer/env_brdf_lut.rs`). The environment term is
// `prefiltered * (F0 * A + B)`.
#ifndef ENV_BRDF_LUT_GLSL
#define ENV_BRDF_LUT_GLSL

// `ENV_BRDF_LUT_SIZE` comes from `include/shader_constants.glsl`.
layout(std430, set = 1, binding = 26) readonly buffer EnvBrdfLutBuffer {{
    vec2 envBrdfLut[];
}};

vec2 envBRDFLut(float NdotV, float roughness) {{
    const int n = int(ENV_BRDF_LUT_SIZE);
    vec2 p = clamp(vec2(NdotV, roughness), 0.0, 1.0) * float(n) - 0.5;
    vec2 p0 = clamp(floor(p), vec2(0.0), vec2(float(n - 2)));
    vec2 t = clamp(p - p0, 0.0, 1.0);
    int x = int(p0.x), y = int(p0.y);
    vec2 a = envBrdfLut[y * n + x];
    vec2 b = envBrdfLut[y * n + x + 1];
    vec2 c = envBrdfLut[(y + 1) * n + x];
    vec2 d = envBrdfLut[(y + 1) * n + x + 1];
    return mix(mix(a, b, t.x), mix(c, d, t.x), t.y);
}}

#endif // ENV_BRDF_LUT_GLSL
"""
    rust = f"""// GENERATED by scripts/gen_env_brdf_lut.py — do not edit by hand.
//! M-LIGHT RLT-IBL-003: the exactly integrated split-sum environment BRDF,
//! (A, B) pairs, NdotV fastest, roughness slowest; uploaded once to set 1
//! binding 26 (`include/env_brdf_lut.glsl`).

// The side is `crate::shader_constants::ENV_BRDF_LUT_SIZE` ({SIZE}).
// The integrator's values at six decimals, as the shader reads them from the storage buffer at
// set 1 binding 26 (`include/env_brdf_lut.glsl` declares the buffer, not the values); a few
// near 1 (`1.000010`) carry a digit f32 cannot hold, which rounds as intended.
#[rustfmt::skip]
#[allow(clippy::excessive_precision)]
pub(super) const ENV_BRDF_LUT: [f32; {2 * SIZE * SIZE}] = [
    {values},
];
"""
    return glsl, rust


def main() -> None:
    glsl, rust = render()
    GLSL_OUT.write_text(glsl)
    RUST_OUT.write_text(rust)
    print(f"wrote {GLSL_OUT} and {RUST_OUT}")


if __name__ == "__main__":
    main()
